import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
const root = process.cwd();
const data = fs.mkdtempSync(path.join(os.tmpdir(), 'whale-follow-test-'));
fs.writeFileSync(path.join(data,'.dshw-size.json'),JSON.stringify({sound:false,vol:0}));
const parity = process.argv.includes('--parity');
const output = path.join(root, parity ? 'work/gpt-parity-verification' : 'work/gpt-desktop-verification');
const env = { ...process.env, WHALE_DESKTOP_TEST: '1', WHALE_COMPLETE_UI_ONLY: '1', WHALE_DESKTOP_VERIFY_DIR: output };
if (process.argv.includes('--live-quota')) env.MURASAME_LIVE_QUOTA_TEST = '1';
delete env.ELECTRON_RUN_AS_NODE;
const child = spawn(path.join(root, 'node_modules/electron/dist/electron.exe'), [path.join(root, parity ? 'dist/gpt-murasame-parity/desktop/main.cjs' : 'dist/gpt-murasame-local/desktop/main.cjs'), '--whale-data=' + data], { env, windowsHide: true, stdio: ['ignore', 'ignore', 'pipe'] });
let errors = ''; child.stderr.on('data', chunk => errors = (errors + chunk).slice(-1800));
const timer = setTimeout(() => child.kill(), 180000);
const [code] = await once(child, 'exit'); clearTimeout(timer);
if (code !== 0) throw new Error('Desktop verification failed: ' + errors);
const report = JSON.parse(fs.readFileSync(path.join(output, 'desktop-follow.json'), 'utf8'));
if (!report.ok) throw new Error(report.error || 'Desktop report failed');
console.log(JSON.stringify({ ok: report.ok, checks: report.checks, fixture: data }));
